三、其他变量的物理解释
- SST：区分表面热通量、水平/垂向平流、混合、夹卷、河流与遥感云污染；具备输入时形成混合层热收支。
- 温盐：解释密度补偿、层结、N²、混合层和跃层；温度单变量不能替代密度稳定度。
- 表层流：区分地转、潮流、Ekman、波致和河口流；速度、单位宽度输运和Sv不可混用。
- 叶绿素与生态：讨论光照、营养盐、层结、混合、平流、浑浊和算法偏差；高叶绿素不自动等于有害藻华或高渔获。

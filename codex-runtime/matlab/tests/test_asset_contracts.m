function must_throw(callback, expected_text)
thrown = false;
try
    callback();
catch error_record
    thrown = true;
    assert(contains(string(error_record.identifier), expected_text) ...
        || contains(string(error_record.message), expected_text), ...
        "Unexpected MATLAB error: %s", error_record.message);
end
assert(thrown, "Expected MATLAB contract rejection containing %s", expected_text);
end

function close_if_valid(figure_handle)
if ~isempty(figure_handle) && isgraphics(figure_handle)
    close(figure_handle);
end
end


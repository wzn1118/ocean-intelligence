function assert_svg_geometry(svg_record, svg_path, reference_width, reference_height)
document = xmlread(char(svg_path));
root = document.getDocumentElement();
assert(strcmpi(char(root.getNodeName()), "svg"), ...
    "test_asset_contracts:InvalidSvg", "SVG has no root element");
measured_width = svg_numeric_length(root, "width");
measured_height = svg_numeric_length(root, "height");
view_box = svg_view_box(root);
assert_close(double(svg_record.width), measured_width, ...
    "SVG width evidence does not match the artifact");
assert_close(double(svg_record.height), measured_height, ...
    "SVG height evidence does not match the artifact");
assert_close(double(svg_record.viewbox_width), view_box(3), ...
    "SVG viewBox width evidence does not match the artifact");
assert_close(double(svg_record.viewbox_height), view_box(4), ...
    "SVG viewBox height evidence does not match the artifact");
assert_close(view_box(3) / view_box(4), measured_width / measured_height, ...
    "SVG viewBox and viewport aspect ratios differ");
assert_close(view_box(3) / view_box(4), ...
    double(reference_width) / double(reference_height), ...
    "SVG and reference raster aspect ratios differ");
end

function value = svg_numeric_length(root, attribute_name)
attribute = strtrim(string(char(root.getAttribute(char(attribute_name)))));
token = regexp(attribute, ...
    "^([-+]?(?:\d+(?:\.\d*)?|\.\d+)(?:[eE][-+]?\d+)?)(?:[A-Za-z%]+)?$", ...
    "tokens", "once");
assert(~isempty(token), "test_asset_contracts:InvalidSvg", ...
    "SVG %s is not an explicit numeric length", attribute_name);
value = str2double(token{1});
assert(isfinite(value) && value > 0, "test_asset_contracts:InvalidSvg", ...
    "SVG %s must be positive", attribute_name);
end

function values = svg_view_box(root)
attribute = string(char(root.getAttribute('viewBox')));
tokens = regexp(attribute, ...
    "[-+]?(?:\d+(?:\.\d*)?|\.\d+)(?:[eE][-+]?\d+)?", "match");
values = str2double(tokens);
assert(numel(values) == 4 && all(isfinite(values)) ...
    && values(3) > 0 && values(4) > 0, ...
    "test_asset_contracts:InvalidSvg", ...
    "SVG viewBox must contain four finite values with positive dimensions");
end

function assert_close(actual, expected, message)
tolerance = 1e-8 * max([1 abs(actual) abs(expected)]);
assert(isfinite(actual) && isfinite(expected) && abs(actual - expected) <= tolerance, ...
    "test_asset_contracts:GeometryMismatch", "%s", message);
end


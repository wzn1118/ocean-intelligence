function result = test_interaction_native_compatibility()
%TEST_INTERACTION_NATIVE_COMPATIBILITY Exercise UI, traditional, and headless paths.
testsDirectory = fileparts(mfilename("fullpath"));
assetsDirectory = fullfile(testsDirectory, "..", "assets");
originalPath = path;
addpath(assetsDirectory);
pathCleanup = onCleanup(@() path(originalPath));

assert_axes_mode_calls_do_not_capture_outputs(assetsDirectory);
data = interaction_fixture();
desktopAvailable = usejava("desktop");

test_static_or_headless_path(data, desktopAvailable);
cjkDefaultFontExecuted = test_publication_layout(data);
test_explicit_font(data);
test_standard_uncertainty(data);
test_time_axis_padding(data);
traditionalDesktopExecuted = false;
uiAxesDesktopExecuted = false;
if desktopAvailable
    test_traditional_desktop_path(data);
    traditionalDesktopExecuted = true;
    if ~verLessThan("matlab", "9.14")
        test_ui_axes_desktop_path(data);
        uiAxesDesktopExecuted = true;
    end
end

result = struct( ...
    "DesktopAvailable", logical(desktopAvailable), ...
    "CJKDefaultFontExecuted", cjkDefaultFontExecuted, ...
    "TraditionalDesktopExecuted", traditionalDesktopExecuted, ...
    "UIAxesDesktopExecuted", uiAxesDesktopExecuted, ...
    "MATLABRelease", string(version('-release')));
fprintf("MATLAB_INTERACTION_NATIVE_COMPATIBILITY=passed\n");
fprintf("MATLAB_INTERACTION_DESKTOP_AVAILABLE=%d\n", desktopAvailable);
fprintf("MATLAB_INTERACTION_UIAXES_EXECUTED=%d\n", uiAxesDesktopExecuted);
fprintf("MATLAB_INTERACTION_CJK_DEFAULT_FONT_EXECUTED=%d\n", cjkDefaultFontExecuted);
clear pathCleanup;
end

function assert_axes_mode_calls_do_not_capture_outputs(assetsDirectory)
sourcePath = fullfile(assetsDirectory, "interactive_timeseries_native_template.m");
sourceText = fileread(sourcePath);
assert(~isempty(regexp(sourceText, ...
    "datacursormode\(axes_handles\(axes_index\), 'on'\)", "once")), ...
    "test_interaction_native_compatibility:MissingDataCursorEnable", ...
    "The UI axes data cursor mode must be enabled explicitly");
assert(~isempty(regexp(sourceText, ...
    "brush\(axes_handles\(axes_index\), 'on'\)", "once")), ...
    "test_interaction_native_compatibility:MissingBrushEnable", ...
    "The UI axes brush mode must be enabled explicitly");
assert(isempty(regexp(sourceText, ...
    "=\s*datacursormode\(axes_handles\(axes_index\)", "once")), ...
    "test_interaction_native_compatibility:DataCursorOutput", ...
    "Axes-targeted datacursormode calls must not request an output");
assert(isempty(regexp(sourceText, ...
    "=\s*brush\(axes_handles\(axes_index\)", "once")), ...
    "test_interaction_native_compatibility:BrushOutput", ...
    "Axes-targeted brush calls must not request an output");
end

function test_static_or_headless_path(data, desktopAvailable)
beforeFigures = findall(groot, "Type", "figure");
requestInteraction = ~desktopAvailable;
outputs = interactive_timeseries_native_template(data, "unused", ...
    "Interactive", requestInteraction, "UseUIFigure", true, ...
    "UseDataCursorCallback", true, "Export", false, ...
    "TimeZone", "UTC", "ValueLabel", "Temperature", ...
    "ValueUnit", "degC");
figureCleanup = onCleanup(@() close_if_valid(outputs.Figure));
assert(~outputs.InteractiveEnabled && ~outputs.UIFigureEnabled, ...
    "test_interaction_native_compatibility:StaticFallback", ...
    "The noninteractive path must use a traditional static figure");
assert(isfield(outputs, "UncertaintyUnit") ...
    && isequal(outputs.UncertaintyUnit, ""), ...
    "test_interaction_native_compatibility:EmptyUncertaintyUnit", ...
    "Output must expose an empty uncertainty unit when uncertainty is absent");
assert(outputs.PublicationWidthPixels == 2400 ...
    && outputs.PublicationHeightPixels == 1500 ...
    && outputs.PublicationDPI == 300 ...
    && outputs.PublicationPhysicalWidthIn == 8 ...
    && outputs.PublicationPhysicalHeightIn == 5, ...
    "test_interaction_native_compatibility:PublicationGeometry", ...
    "The default publication export geometry must remain 8 by 5 inches at 300 DPI");
verify_publication_layout(outputs, [8 5]);
verify_default_font(outputs);
if ~desktopAvailable
    assert(outputs.HeadlessFallbackUsed, ...
        "test_interaction_native_compatibility:HeadlessFallback", ...
        "A requested headless interaction must report its fallback");
end
verify_stable_selection(outputs, data);
lineHandle = outputs.Lines(1);
close(outputs.Figure);
assert(~isgraphics(outputs.Figure) ...
    && isempty(outputs.GetSelectedObservationIDs()) ...
    && isequal(outputs.DataCursorUpdateFcn([], ...
        struct("Target", lineHandle, "DataIndex", 1)), ...
        {'Data tip unavailable'}), ...
    "test_interaction_native_compatibility:StaticCleanup", ...
    "Static or headless cleanup left unsafe callbacks or selection state");
clear figureCleanup;
assert(numel(findall(groot, "Type", "figure")) == numel(beforeFigures), ...
    "test_interaction_native_compatibility:StaticFigureLeak", ...
    "The static or headless path leaked a figure");
end


function test_ui_axes_desktop_path(data)
beforeFigures = findall(groot, "Type", "figure");
outputs = interactive_timeseries_native_template(data, "unused", ...
    "Interactive", true, "UseUIFigure", true, ...
    "UseDataCursorCallback", false, "Export", false, ...
    "PublicationWidthPixels", 1400, "PublicationHeightPixels", 1200, ...
    "PublicationDPI", 200, ...
    "TimeZone", "UTC", "ValueLabel", "Temperature", ...
    "ValueUnit", "degC");
figureCleanup = onCleanup(@() close_if_valid(outputs.Figure));
assert(outputs.InteractiveEnabled && outputs.UIFigureEnabled, ...
    "test_interaction_native_compatibility:UIAxesDesktop", ...
    "The uifigure desktop path did not enable UI axes interaction");
assert(string(outputs.Figure.Units) == "pixels" ...
    && isequal(outputs.Figure.Position(3:4), [1200 720]) ...
    && string(outputs.Layout.Units) == "normalized" ...
    && all(abs(outputs.Layout.OuterPosition - [0 0 1 1]) < 1e-6), ...
    "test_interaction_native_compatibility:UIFigureGeometry", ...
    "Publication dimensions and page margins must not change the UI figure layout");
interactionState = getappdata(outputs.Figure, "OceanInteractionState");
assert(isequal(interactionState.UsesAxesInteractionModes, true) ...
    && all(cellfun(@isempty, interactionState.DataCursorModes)) ...
    && all(cellfun(@isempty, interactionState.BrushModes)), ...
    "test_interaction_native_compatibility:UIAxesModeObjects", ...
    "UI axes interaction must not depend on returned mode objects");
verify_stable_selection(outputs, data);
lineHandle = outputs.Lines(1);
close(outputs.Figure);
assert(~isgraphics(outputs.Figure) ...
    && isempty(outputs.GetSelectedObservationIDs()) ...
    && isequal(outputs.DataCursorUpdateFcn([], ...
        struct("Target", lineHandle, "DataIndex", 1)), ...
        {'Data tip unavailable'}), ...
    "test_interaction_native_compatibility:UIAxesCleanup", ...
    "UI axes cleanup left unsafe callbacks or selection state");
clear figureCleanup;
assert(numel(findall(groot, "Type", "figure")) == numel(beforeFigures), ...
    "test_interaction_native_compatibility:UIAxesFigureLeak", ...
    "The uifigure desktop path leaked a figure");
end

function verify_stable_selection(outputs, data)
outputs.Lines(1).BrushData = [1; 0; 1; 0];
identity = outputs.GetSelectedObservationIdentity();
assert(isequal(identity.ObservationID, data.ObservationID([1 3])) ...
    && isequal(identity.SourceRow, data.SourceRow([1 3])), ...
    "test_interaction_native_compatibility:StableIdentity", ...
    "Brush selection did not preserve ObservationID and SourceRow");
identityAgain = outputs.GetSelectedObservationIdentity();
assert(isequal(identityAgain, identity), ...
    "test_interaction_native_compatibility:StableReentry", ...
    "Repeated brush selection collection was not stable");
outputs.ClearBrushSelection();
assert(isempty(outputs.GetSelectedObservationIDs()), ...
    "test_interaction_native_compatibility:ClearSelection", ...
    "Brush selection was not cleared");
end


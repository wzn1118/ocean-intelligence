function verify_publication_layout(outputs, expectedSize)
assert(string(outputs.Figure.Units) == "inches" ...
    && all(abs(outputs.Figure.Position(3:4) - expectedSize) < 1e-6) ...
    && string(outputs.Figure.PaperUnits) == "inches" ...
    && all(abs(outputs.Figure.PaperSize - expectedSize) < 1e-6) ...
    && all(abs(outputs.Figure.PaperPosition - [0 0 expectedSize]) < 1e-6) ...
    && string(outputs.Figure.PaperPositionMode) == "manual", ...
    "test_interaction_native_compatibility:PreExportPhysicalSize", ...
    "Traditional figures must have publication physical dimensions before export");
outerPosition = outputs.Layout.OuterPosition;
pageMargins = [outerPosition(1:2), ...
    1 - outerPosition(1:2) - outerPosition(3:4)] .* [expectedSize expectedSize];
assert(string(outputs.Layout.Units) == "normalized" ...
    && string(outputs.Layout.PositionConstraint) == "outerposition" ...
    && all(abs(pageMargins - 0.25) < 1e-6) ...
    && string(outputs.Layout.Padding) == "loose", ...
    "test_interaction_native_compatibility:PublicationPageMargins", ...
    "The complete tiled layout must reserve quarter-inch page margins");
end


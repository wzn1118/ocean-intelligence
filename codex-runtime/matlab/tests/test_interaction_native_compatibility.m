function test_standard_uncertainty(data)
data.Value(2) = NaN;
data.Uncertainty = [0.11; NaN; NaN; 0.23];
data.Properties.VariableUnits{end} = 'degC';
for typeInput = ["standard-uncertainty" "standard_uncertainty" "standard-deviation"]
    expectedType = replace(typeInput, "_", "-");
    outputs = render_uncertainty(data, typeInput);
    figureCleanup = onCleanup(@() close_if_valid(outputs.Figure));
    assert(isfield(outputs, "UncertaintyUnit") ...
        && isequal(outputs.UncertaintyUnit, "degC"), ...
        "test_interaction_native_compatibility:UncertaintyUnitField", ...
        "Output must expose the validated uncertainty unit as a scalar string");
    metadata = outputs.Lines(1).UserData;
    assert(outputs.UncertaintyType == expectedType ...
        && outputs.UncertaintyUnit == "degC" && isnan(outputs.ConfidenceLevel) ...
        && outputs.UncertaintyRepresentation == "magnitude" ...
        && metadata.UncertaintyType == expectedType ...
        && metadata.UncertaintyUnit == "degC" && metadata.QuantityUnit == "degC" ...
        && isequaln(metadata.Uncertainty, data.Uncertainty) ...
        && isequaln(metadata.PlottedValue, data.Value) ...
        && isequaln(outputs.Lines(1).YData(:), data.Value), ...
        "test_interaction_native_compatibility:UncertaintySemantics", ...
        "Uncertainty type, unit, and raw values must survive without statistical reinterpretation");
    assert(outputs.ValidCount == 2 && outputs.MissingCount == 2 ...
        && outputs.UncertaintyMissingCount == 1, ...
        "test_interaction_native_compatibility:UncertaintyMissing", ...
        "Adding an uncertainty type must preserve existing missing-data counts");
    for dataIndex = [1 4]
        tipRows = outputs.DataCursorUpdateFcn([], ...
            struct("Target", outputs.Lines(1), "DataIndex", dataIndex));
        expectedTip = sprintf('Uncertainty (%s, degC): %.6g', ...
            char(expectedType), data.Uncertainty(dataIndex));
        assert(any(strcmp(tipRows, expectedTip)), ...
            "test_interaction_native_compatibility:UncertaintyDataTip", ...
            "Data cursor uncertainty must retain the declared type, unit, and magnitude");
    end
    missingTip = outputs.DataCursorUpdateFcn([], ...
        struct("Target", outputs.Lines(1), "DataIndex", 2));
    incompleteTip = outputs.DataCursorUpdateFcn([], ...
        struct("Target", outputs.Lines(1), "DataIndex", 3));
    assert(isequal(missingTip, {'Data tip unavailable'}) ...
        && ~any(startsWith(string(incompleteTip), "Uncertainty (")), ...
        "test_interaction_native_compatibility:MissingUncertaintyDataTip", ...
        "Missing values or uncertainty must not be inferred by data cursors");
    clear figureCleanup;
end
for unknownType = ["variance" "std" "standard uncertainty"]
    assert_interaction_error(@() render_uncertainty(data, unknownType), ...
        "supported scientific uncertainty semantic");
end
assert_interaction_error(@() render_uncertainty(data, "standard-uncertainty", ...
    "ConfidenceLevel", 0.95), "ConfidenceLevel applies only");
for invalidLevel = [NaN 0 1 Inf]
    assert_interaction_error(@() render_uncertainty(data, "confidence-interval", ...
        "ConfidenceLevel", invalidLevel), "ConfidenceLevel must be an explicit fraction");
end
assert_interaction_error(@() interactive_timeseries_native_template(data, "unused", ...
    "Interactive", false, "Export", false, "TimeZone", "UTC", ...
    "ValueLabel", "Temperature", "ValueUnit", "degC", ...
    "UncertaintyType", "standard-uncertainty", "UncertaintyUnit", "K"), ...
    "UncertaintyUnit must match ValueUnit");
invalidData = data;
invalidData.Uncertainty(2) = 0.1;
assert_interaction_error(@() render_uncertainty(invalidData, "standard-uncertainty"), ...
    "Finite uncertainty cannot exist where Value is missing");
end


function validate_provenance(provenance, source, generatedReport, fixture, pageInches, labels)
assert(provenance.schema_version == 1 ...
    && string(provenance.scope) == "isolated_builtin_codex_generation_only" ...
    && isequal(provenance.generated_source_edited, false) ...
    && string(provenance.matlab_execution_status) == "not_run" ...
    && isequal(provenance.visual_verified, false) ...
    && isequal(provenance.desktop_interaction_verified, false) ...
    && isequal(provenance.real_ocean_observations, false), ...
    'test_astra_generated_comparison:Provenance', 'Generation must not claim prior native or visual acceptance');
records = {source, generatedReport, fixture};
fields = {'source', 'report', 'fixture'};
for recordIndex = 1:numel(records)
    declared = provenance.(fields{recordIndex});
    actual = records{recordIndex};
    assert(string(declared.file) == actual.file && declared.bytes == actual.bytes ...
        && strcmpi(declared.sha256, actual.sha256), ...
        'test_astra_generated_comparison:ProvenanceBinding', 'Source/report/fixture provenance differs from bytes');
end
assert(isequal(provenance.fixture.synthetic, true) ...
    && string(provenance.generation.thread_id) == "01a07422-6d4a-7052-8d6a-993e40f9d46a" ...
    && string(provenance.generation.cli_version) == "0.153.4" ...
    && string(provenance.generation.provider_id_from_session_meta) == "OpenAI" ...
    && string(provenance.generation.model_from_both_turn_contexts) == "gpt-6-astra" ...
    && string(provenance.generation.effort) == "high" ...
    && numel(provenance.generation.turns) == 2 ...
    && all(string({provenance.generation.turns.status}) == "completed") ...
    && string(provenance.generation_snapshot.local_commit) == "587c382a7155c265abb82137b6e5ce47717b8de0", ...
    'test_astra_generated_comparison:GenerationOrigin', 'Expected the recorded original two-turn generation');
assert(isequal(provenance.observed_output_contract.page_inches(:)', pageInches) ...
    && string(provenance.observed_output_contract.xlabel) == labels(1) ...
    && string(provenance.observed_output_contract.ylabel) == labels(2), ...
    'test_astra_generated_comparison:ObservedContract', 'Preserve the reviewed original page and descriptive labels');
end

function geometry = inspect_figure(figureHandle, result, previousFigures, pageInches, titleText)
createdFigures = new_figures(previousFigures);
assert(isscalar(figureHandle) && isgraphics(figureHandle, 'figure') ...
    && isscalar(createdFigures) && isequal(createdFigures, figureHandle) ...
    && string(figureHandle.Visible) == "off" && string(figureHandle.Units) == "inches" ...
    && all(abs(double(figureHandle.Position(3:4)) - pageInches) <= 1e-10), ...
    'test_astra_generated_comparison:Figure', 'Require the one original invisible 10x8.5-inch figure');
assert(isstruct(result) && isscalar(result) && isgraphics(result.Axes, 'axes') ...
    && isequal(findall(figureHandle, 'Type', 'axes'), result.Axes) ...
    && isequal(ancestor(result.Axes, 'figure'), figureHandle) ...
    && string(result.Axes.Title.String) == string(titleText) ...
    && string(result.Axes.Title.Visible) == "on", ...
    'test_astra_generated_comparison:Axes', 'The returned axes and original title must belong to the same figure');
reference = result.OneToOne;
assert(isscalar(reference) && isgraphics(reference, 'line') ...
    && isequal(reference.Parent, result.Axes) && string(reference.Visible) == "on" ...
    && string(reference.LineStyle) ~= "none" && reference.LineWidth > 0, ...
    'test_astra_generated_comparison:ReferenceLine', 'The original 1:1 reference must remain visible');
geometry = struct('units', string(figureHandle.Units), 'position', double(figureHandle.Position), ...
    'axes_units', string(result.Axes.Units), 'axes_position', double(result.Axes.Position), ...
    'xlabel', string(result.Axes.XLabel.String), 'ylabel', string(result.Axes.YLabel.String), ...
    'title', string(result.Axes.Title.String), 'font_name', string(result.Axes.FontName), ...
    'screen_pixels_per_inch', get(groot, 'ScreenPixelsPerInch'), 'display', string(getenv('DISPLAY')));
end

function assert_complete_v3(evidence)
assert(evidence.schema_version == 3 && isequal(evidence.shape, {12}) ...
    && isequal(evidence.dimension_order, {'observation'}) ...
    && numel(evidence.records.ids) == 12 && numel(evidence.records.time_utc) == 12 ...
    && numel(evidence.records.depth_m) == 12 ...
    && isequal(cell2mat(evidence.records.source_rows), (1:12)') ...
    && numel(evidence.input_values.observation) == 12 && numel(evidence.input_values.model) == 12 ...
    && isnan(evidence.input_values.observation{12}) && evidence.input_values.model{12} == 13.96 ...
    && numel(evidence.native_scatter.x_values) == 11 && numel(evidence.native_scatter.y_values) == 11 ...
    && numel(evidence.uncertainty.segments) == 11, ...
    'test_astra_generated_comparison:CompleteV3', 'Retain 12 complete records, 11 pairs and 11 native intervals');
wire = jsondecode(jsonencode(evidence));
assert(numel(wire.records.ids) == 12 && numel(wire.input_values.observation) == 12 ...
    && isnan(wire.input_values.observation(12)) && wire.input_values.model(12) == 13.96 ...
    && numel(wire.qc.observation.flags) == 12 && strcmp(wire.qc.observation.flags{6}, 'suspect') ...
    && numel(wire.uncertainty.observation.values) == 12 && isnan(wire.uncertainty.observation.values(12)) ...
    && isstruct(wire.uncertainty.segments) && numel(wire.uncertainty.segments) == 11 ...
    && islogical(wire.pairing.finite_pair_mask) && islogical(wire.pairing.paired_mask) ...
    && islogical(wire.qc.accepted_mask) && islogical(wire.uncertainty.graphics_mask) ...
    && isequal(fieldnames(wire.qc.model), {'status'}) ...
    && strcmp(wire.qc.model.status, 'not_provided') ...
    && isequal(fieldnames(wire.uncertainty.model), {'status'}) ...
    && strcmp(wire.uncertainty.model.status, 'not_provided'), ...
    'test_astra_generated_comparison:JSONRoundTrip', 'JSON must preserve full QC/U arrays, nulls and masks');
end

function records = verify_exports(directory, entry, pixelSize, pageInches, dpi)
assert(isequal(sort(string(fieldnames(entry.exports))), sort(["png"; "pdf"; "svg"])), ...
    'test_astra_generated_comparison:Formats', 'Exactly PNG, PDF and SVG must be present');
records = repmat(file_record(fullfile(directory, entry.exports.png.file)), 0, 1);
for format = ["png", "pdf", "svg"]
    exported = entry.exports.(format);
    assert(string(exported.file) == string(entry.id) + "." + format, ...
        'test_astra_generated_comparison:ExportPath', 'Unexpected export path');
    actual = file_record(fullfile(directory, exported.file));
    assert(actual.bytes == exported.bytes && strcmpi(actual.sha256, exported.sha256) ...
        && string(exported.export_api) == string(entry.runtime.export_api.(format)), ...
        'test_astra_generated_comparison:ArtifactBinding', 'Actual artifact and API must match the manifest');
    records(end + 1, 1) = actual; %#ok<AGROW>
end
png = imfinfo(fullfile(directory, entry.exports.png.file));
assert(png.Width == pixelSize(1) && png.Height == pixelSize(2) ...
    && entry.exports.png.dpi == dpi ...
    && all(abs([entry.exports.pdf.width entry.exports.pdf.height] - pageInches * 72) <= 1) ...
    && entry.exports.pdf.pages == 1 ...
    && entry.exports.svg.width == pixelSize(1) && entry.exports.svg.height == pixelSize(2), ...
    'test_astra_generated_comparison:Dimensions', 'Preserve 3000x2550 at 300 DPI and the original physical page');
end

function assert_function_paths(names, paths)
for functionIndex = 1:numel(names)
    actual = which(char(names(functionIndex)));
    assert(~isempty(actual) && canonical_path(actual) == paths(functionIndex), ...
        'test_astra_generated_comparison:FunctionPath', 'Unexpected implementation of %s', names(functionIndex));
end
end

function assert_files_unchanged(records)
for recordIndex = 1:numel(records)
    actual = file_record(records(recordIndex).path);
    assert(actual.bytes == records(recordIndex).bytes ...
        && strcmpi(actual.sha256, records(recordIndex).sha256), ...
        'test_astra_generated_comparison:FileChanged', 'File changed during trial: %s', actual.path);
end
end

function record = file_record(pathValue)
pathValue = canonical_path(pathValue);
info = dir(pathValue);
assert(isscalar(info) && ~info.isdir && info.bytes > 0, ...
    'test_astra_generated_comparison:MissingFile', 'Expected nonempty file: %s', pathValue);
[~, name, extension] = fileparts(pathValue);
record = struct('file', string(name) + string(extension), 'path', pathValue, ...
    'bytes', info.bytes, 'sha256', string(oi_sha256_file(pathValue)));
end

function value = canonical_path(value)
[found, attributes] = fileattrib(char(value));
assert(found, 'test_astra_generated_comparison:MissingPath', 'Missing path: %s', value);
value = string(attributes.Name);
if usejava('jvm')
    value = string(char(java.io.File(char(value)).getCanonicalPath()));
end
end

function value = read_json(filePath)
fileHandle = fopen(filePath, 'rb');
assert(fileHandle >= 0, 'test_astra_generated_comparison:Read', 'Cannot read %s', filePath);
cleanup = onCleanup(@() fclose(fileHandle));
content = fread(fileHandle, Inf, '*uint8');
value = jsondecode(native2unicode(content', 'UTF-8'));
clear cleanup;
end

function write_json(filePath, value)
fileHandle = fopen(filePath, 'wb');
assert(fileHandle >= 0, 'test_astra_generated_comparison:Write', 'Cannot write %s', filePath);
cleanup = onCleanup(@() fclose(fileHandle));
content = unicode2native(jsonencode(value), 'UTF-8');
assert(fwrite(fileHandle, content, 'uint8') == numel(content), ...
    'test_astra_generated_comparison:Write', 'Incomplete evidence write: %s', filePath);
clear cleanup;
end

function handles = new_figures(previousFigures)
handles = findall(groot, 'Type', 'figure');
keep = true(size(handles));
for handleIndex = 1:numel(handles)
    keep(handleIndex) = ~any(handles(handleIndex) == previousFigures(isgraphics(previousFigures)));
end
handles = handles(keep);
end

function close_new_figures(previousFigures)
handles = new_figures(previousFigures);
for handleIndex = 1:numel(handles)
    if isgraphics(handles(handleIndex), 'figure')
        delete(handles(handleIndex));
    end
end
end

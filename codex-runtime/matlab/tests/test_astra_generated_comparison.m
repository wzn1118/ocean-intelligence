function report = test_astra_generated_comparison(outputDirectory, fixturePath, expectedSourceHash, generationRound)
arguments
    outputDirectory (1,1) string
    fixturePath (1,1) string
    expectedSourceHash (1,1) string
    generationRound (1,1) string = "round22"
end
assert(~exist('OCTAVE_VERSION', 'builtin'), ...
    'test_astra_generated_comparison:MatlabRequired', 'This trial requires MATLAB');
assert(isfolder(outputDirectory), 'test_astra_generated_comparison:OutputDirectory', ...
    'The caller must supply an existing output directory');
testsDirectory = fileparts(mfilename('fullpath'));
matlabDirectory = fileparts(testsDirectory);
assetsDirectory = canonical_path(fullfile(matlabDirectory, 'assets'));
evalDirectory = canonical_path(fullfile(matlabDirectory, 'evals'));
assert(any(generationRound == ["round22", "round23"]), ...
    'test_astra_generated_comparison:GenerationRound', 'Unknown pinned generation round');
pins = generation_pins(generationRound);
bundleDirectory = canonical_path(fullfile(testsDirectory, "model-generated-" + generationRound));
trialDirectory = fullfile(canonical_path(outputDirectory), 'astra-comparison-trial');
assert(~isfolder(trialDirectory) && ~isfile(trialDirectory), ...
    'test_astra_generated_comparison:StaleOutput', 'Trial output must be fresh: %s', trialDirectory);
[created, message] = mkdir(trialDirectory);
assert(created, 'test_astra_generated_comparison:CreateDirectory', '%s', message);
evidencePath = fullfile(trialDirectory, 'astra-generated-comparison-evidence.json');
originalPath = path;
originalDirectory = pwd;
previousFigures = findall(groot, 'Type', 'figure');
pathCleanup = onCleanup(@() path(originalPath));
directoryCleanup = onCleanup(@() cd(originalDirectory));
figureCleanup = onCleanup(@() close_new_figures(previousFigures));
profile = "astra-temperature-labels";
pageInches = [10 8.5];
pixelSize = [3000 2550];
dpi = 300;
expectedLabels = ["Observation temperature (degC)", "Model temperature (degC)"];
report = struct('schema_version', 1, 'scope', 'model_generated_synthetic_comparison_only', ...
    'status', 'running', 'phase', 'preflight', 'matlab_release', "R" + string(version('-release')), ...
    'matlab_version', string(version), 'matlab_call_completed', false, ...
    'execution_verified', false, 'native_proof_status', 'not_run', ...
    'export_status', 'not_run', 'manifest_status', 'not_run', ...
    'visual_verified', false, 'desktop_interaction_verified', false, ...
    'real_ocean_observations', false, 'reader_profile', profile, ...
    'ci_run_id', string(getenv('GITHUB_RUN_ID')), 'ci_job', string(getenv('GITHUB_JOB')), ...
    'execution_commit', string(getenv('GITHUB_SHA')));
report.requested_output = struct('page_inches', pageInches, 'pixels', pixelSize, 'dpi', dpi);
report.generation_round = generationRound;
try
    addpath(assetsDirectory, evalDirectory, bundleDirectory, '-begin');
    clear astra_comparison_trial;
    rehash;
    dependencyNames = ["measure_comparison_plot_data", "oi_plot_comparison", ...
        "oi_export_figure", "oi_write_manifest", "oi_figure", "oi_ocean_theme", ...
        "oi_apply_axes", "oi_sha256_file", "oi_read_file_prefix", "oi_font_available"];
    dependencyPaths = strings(size(dependencyNames));
    for dependencyIndex = 1:numel(dependencyNames)
        directory = assetsDirectory;
        if dependencyNames(dependencyIndex) == "measure_comparison_plot_data"
            directory = evalDirectory;
        end
        dependencyPaths(dependencyIndex) = canonical_path( ...
            fullfile(directory, dependencyNames(dependencyIndex) + ".m"));
    end
    sourcePath = canonical_path(fullfile(bundleDirectory, 'astra_comparison_trial.m'));
    functionNames = [dependencyNames, "astra_comparison_trial"];
    functionPaths = [dependencyPaths, sourcePath];
    assert_function_paths(functionNames, functionPaths);
    executionPath = path;
    source = file_record(sourcePath);
    assert(strcmpi(expectedSourceHash, pins.source_sha256) ...
        && source.bytes == pins.source_bytes && strcmpi(source.sha256, expectedSourceHash), ...
        'test_astra_generated_comparison:SourceHash', ...
        'Only the explicitly pinned, unchanged generated source may execute');
    generatedReport = file_record(fullfile(bundleDirectory, 'astra_comparison_trial.md'));
    assert(generatedReport.bytes == pins.report_bytes && strcmpi(generatedReport.sha256, pins.report_sha256), ...
        'test_astra_generated_comparison:ReportHash', 'Original generated report bytes changed');
    prompt = file_record(fullfile(bundleDirectory, 'generation-prompt.zh.txt'));
    assert(prompt.bytes == pins.prompt_bytes && strcmpi(prompt.sha256, pins.prompt_sha256), ...
        'test_astra_generated_comparison:PromptHash', 'Original generation prompt bytes changed');
    provenanceRecord = file_record(fullfile(bundleDirectory, 'generation-provenance.json'));
    assert(strcmpi(provenanceRecord.sha256, pins.provenance_sha256), ...
        'test_astra_generated_comparison:ProvenanceHash', 'Pinned generation provenance bytes changed');
    provenance = read_json(provenanceRecord.path);
    fixtureRecord = file_record(fixturePath);
    assert(fixtureRecord.bytes == 2771 && strcmpi(fixtureRecord.sha256, ...
        'dfdd4a9b3270151e02b8c91970775ed10ebfc862bc8119c3cccb85b99b6f676b'), ...
        'test_astra_generated_comparison:FixtureHash', 'The supplied fixture must be the pinned paired input');
    fixture = read_json(fixtureRecord.path);
    assert(fixture.schema_version == 1 && isequal(fixture.synthetic, true) ...
        && string(fixture.id) == "paired-observation-model" && numel(fixture.records) == 12, ...
        'test_astra_generated_comparison:Fixture', 'Expected all 12 original synthetic records');
    validate_provenance(provenance, source, generatedReport, fixtureRecord, pageInches, expectedLabels);
    trackedFiles = [source; generatedReport; prompt; provenanceRecord; fixtureRecord; ...
        file_record(string(mfilename('fullpath')) + ".m")];
    for dependencyIndex = 1:numel(dependencyPaths)
        trackedFiles(end + 1, 1) = file_record(dependencyPaths(dependencyIndex)); %#ok<AGROW>
    end
    report.source = source;
    report.expected_source_sha256 = expectedSourceHash;
    report.generated_report = generatedReport;
    report.prompt = prompt;
    report.provenance = provenanceRecord;
    report.generation_provenance = provenance;
    report.provenance_scope = 'coordinator_record_hash_binding_not_model_authentication';
    report.input = fixtureRecord;
    report.execution_files = trackedFiles;
    inputSnapshot = struct('id', string(fixture.id), 'sha256', fixtureRecord.sha256);
    report.phase = 'construction';
    fprintf('ASTRA_COMPARISON_TRIAL_BEGIN=%s\n', source.sha256);
    [figureHandle, result] = astra_comparison_trial(fixtureRecord.path);
    report.matlab_call_completed = true;
    assert(strcmp(path, executionPath) && strcmp(pwd, originalDirectory), ...
        'test_astra_generated_comparison:EnvironmentChanged', 'Generated code changed path or working directory');
    assert_function_paths(functionNames, functionPaths);
    assert_files_unchanged(trackedFiles);
    report.phase = 'native-before-export';
    report.figure_before_export = inspect_figure( ...
        figureHandle, result, previousFigures, pageInches, fixture.title);
    before = measure_comparison_plot_data(result, fixture, inputSnapshot, figureHandle, profile);
    assert_complete_v3(before);
    report.native_proof_status = 'passed_before_export';
    report.native_before_export = before;
    report.phase = 'export';
    theme = getappdata(figureHandle, 'OI_OceanTheme');
    entry = oi_export_figure(figureHandle, trialDirectory, string(fixture.id), ...
        pixelSize(1), pixelSize(2), dpi, 'Title', string(fixture.title), ...
        'Source', "Model-generated trial: tests/model-generated-" + generationRound + "/astra_comparison_trial.m", ...
        'Theme', string(theme.Name), 'ExportSVG', true);
    report.export_status = 'completed';
    report.phase = 'native-after-export';
    report.figure_after_export = inspect_figure( ...
        figureHandle, result, previousFigures, pageInches, fixture.title);
    after = measure_comparison_plot_data(result, fixture, inputSnapshot, figureHandle, profile);
    assert_complete_v3(after);
    assert(isequaln(before, after), 'test_astra_generated_comparison:ExportMutation', ...
        'Export changed the complete native v3 declaration of the generated figure');
    report.native_proof_status = 'passed_before_and_after_export';
    report.plot_data_evidence = after;
    report.phase = 'manifest';
    manifestPath = fullfile(trialDirectory, 'figures.json');
    oi_write_manifest(manifestPath, entry);
    manifest = read_json(manifestPath);
    assert(numel(manifest.figures) == 1 ...
        && string(manifest.figures.id) == string(after.figure_id) ...
        && isequaln(manifest.figures.exports, jsondecode(jsonencode(entry.exports))), ...
        'test_astra_generated_comparison:ManifestBinding', 'Manifest must bind the same generated figure exports');
    artifacts = verify_exports(trialDirectory, entry, pixelSize, pageInches, dpi);
    report.exports = entry.exports;
    report.export_api = entry.runtime.export_api;
    report.artifacts = artifacts;
    report.manifest = file_record(manifestPath);
    report.manifest_status = 'passed';
    report.phase = 'final-integrity';
    assert_function_paths(functionNames, functionPaths);
    assert_files_unchanged([trackedFiles; artifacts; report.manifest]);
    assert(strcmp(path, executionPath) && strcmp(pwd, originalDirectory), ...
        'test_astra_generated_comparison:EnvironmentChanged', 'Trial changed path or working directory');
    report.original_files_unchanged = true;
    report.status = 'passed';
    report.phase = 'complete';
    report.execution_verified = true;
    write_json(evidencePath, report);
    fprintf('ASTRA_COMPARISON_TRIAL_PROFILE=%s\n', profile);
    fprintf('ASTRA_COMPARISON_TRIAL=passed_synthetic_native_v3_and_exports_only\n');
catch trialError
    report.status = 'failed';
    report.execution_verified = false;
    report.error_identifier = string(trialError.identifier);
    report.error_message = string(trialError.message);
    report.error_report = string(getReport(trialError, 'extended', 'hyperlinks', 'off'));
    try
        write_json(evidencePath, report);
    catch evidenceError
        warning('test_astra_generated_comparison:FailureEvidence', ...
            'Cannot record trial failure: %s', evidenceError.message);
    end
    fprintf('ASTRA_COMPARISON_TRIAL_FAILED=%s:%s\n', report.phase, trialError.identifier);
    rethrow(trialError);
end
clear figureCleanup directoryCleanup pathCleanup;
end


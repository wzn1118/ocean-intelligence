    "AccentColor", [0 0.60 0.65], ...
    "LineColors", [0 0.36 0.55; 0 0.62 0.65; 0.93 0.46 0.16], ...
    "SequentialMap", parula(64), "DivergingMap", cool(65), ...
    "Name", "family-a-test");
end

function [figureHandle, axesHandle] = make_axes()
figureHandle = figure("Visible", "off", "Color", "w");
axesHandle = axes(figureHandle);
end

function must_throw(action, identifierFragment)
didThrow = false;
try
    action();
catch errorValue
    didThrow = contains(string(errorValue.identifier), identifierFragment) ...
        || contains(string(errorValue.message), identifierFragment);
end
assert(didThrow, "full100_family_a:ExpectedError", ...
    "Expected an error containing '%s'", identifierFragment);
end

function close_if_valid(figureHandle)
if ~isempty(figureHandle) && isgraphics(figureHandle)
    close(figureHandle);
end
end

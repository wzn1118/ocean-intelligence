function evidence = measure_comparison_plot_data(result, fixture, input_snapshot, figure_handle, text_profile)
if nargin < 5
    text_profile = "fixture-default";
end
assert((ischar(text_profile) && isrow(text_profile)) ...
    || (isstring(text_profile) && isscalar(text_profile)), ...
    "run_matlab_gate:ComparisonProofTextProfile", "Text profile must be a scalar name");
text_profile = string(text_profile);
assert(~ismissing(text_profile) ...
    && any(text_profile == ["fixture-default", "astra-temperature-labels"]), ...
    "run_matlab_gate:ComparisonProofTextProfile", "Unsupported comparison text profile");
expected_axis_labels = ["Observation (degC)", "Model (degC)"];
if text_profile == "astra-temperature-labels"
    expected_axis_labels = ["Observation temperature (degC)", "Model temperature (degC)"];
end
assert(string(fixture.id) == "paired-observation-model" ...
    && string(input_snapshot.id) == string(fixture.id), ...
    "run_matlab_gate:ComparisonProofScope", "Comparison v3 requires the bound paired fixture");
records = fixture.records;
sample_count = numel(records);
expected_ids = reshape(string({records.id}), [], 1);
expected_time = parse_utc_time(string({records.time}));
expected_depth = numeric_record_field(records, "depth_m");
expected_observation = numeric_record_field(records, "observation_degC");
expected_model = numeric_record_field(records, "model_degC");
expected_uncertainty = numeric_record_field(records, "uncertainty_degC");
expected_qc = reshape(string({records.qc}), [], 1);
expected_rows = (1:sample_count)';
expected_accepted = ["good"; "suspect"];
finite_mask = isfinite(expected_observation) & isfinite(expected_model);
qc_mask = ismember(expected_qc, expected_accepted);
paired_mask = finite_mask & qc_mask;
graphics_mask = paired_mask & isfinite(expected_uncertainty);
assert(string(fixture.contract.time_zone) == "UTC" ...
    && string(fixture.contract.depth_direction) == "positive_down" ...
    && string(fixture.contract.observation_unit) == "degC" ...
    && string(fixture.contract.model_unit) == "degC" ...
    && string(fixture.contract.uncertainty_unit) == "degC" ...
    && string(fixture.contract.uncertainty_type) == "standard_uncertainty" ...
    && string(fixture.contract.missing_policy) == "preserve" ...
    && string(fixture.contract.qc_policy) == "preserve" ...
    && ~any(finite_mask & ~qc_mask), ...
    "run_matlab_gate:ComparisonProofSemantics", ...
    "The comparison profile must preserve finite pairs and observation standard uncertainty in degC");

record_data = result.RecordData;
record_fields = {'RecordID', 'Time', 'Depth', 'DepthUnit', 'DepthDirection', ...
    'SourceRow', 'SourceRowOrigin', 'Observation', 'Model'};
assert(isstruct(record_data) && isscalar(record_data) ...
    && isequal(sort(fieldnames(record_data)), sort(record_fields(:))) ...
    && isequal(string(record_data.RecordID(:)), expected_ids) ...
    && isdatetime(record_data.Time) && string(record_data.Time.TimeZone) == "UTC" ...
    && isequal(record_data.Time(:), expected_time) ...
    && isequal(record_data.Depth(:), expected_depth) ...
    && string(record_data.DepthUnit) == "m" ...
    && string(record_data.DepthDirection) == "positive_down" ...
    && isequal(record_data.SourceRow(:), expected_rows) ...
    && string(record_data.SourceRowOrigin) == "call_entry_order" ...
    && isequaln(record_data.Observation(:), expected_observation) ...
    && isequaln(record_data.Model(:), expected_model), ...
    "run_matlab_gate:ComparisonProofRecords", ...
    "Returned pre-filter identity and both value arrays must retain every ordered fixture record");
assert(string(result.PairingRule) == "row-aligned" ...
    && isequal(result.ObservationPairIndices(:), expected_rows) ...
    && isequal(result.ModelPairIndices(:), expected_rows) ...
    && isequal(result.FinitePairMask(:), finite_mask) ...
    && isequal(result.PairedMask(:), paired_mask) ...
    && isequal(result.QCAcceptedMask(:), qc_mask) ...
    && result.UnmatchedObservationCount == 0 && result.UnmatchedModelCount == 0 ...
    && string(result.DuplicateKeyPolicy) == "reject" ...
    && string(result.MissingPolicy) == "preserve" ...
    && result.MissingCount == sum(~finite_mask) ...
    && result.QCRejectedCount == sum(finite_mask & ~qc_mask) ...
    && result.ValidCount == sum(paired_mask), ...
    "run_matlab_gate:ComparisonProofPairing", ...
    "Pair indices, missingness, QC acceptance and counts must match independent fixture operands");
qc = result.QC;
assert(isstruct(qc) && isscalar(qc) ...
    && isequal(sort(fieldnames(qc)), sort({'Observation'; 'Model'; 'AcceptedValues'})) ...
    && isequal(sort(fieldnames(qc.Observation)), sort({'Status'; 'Flags'})) ...
    && string(qc.Observation.Status) == "provided" ...
    && isequal(string(qc.Observation.Flags(:)), expected_qc) ...
    && isequal(string(qc.AcceptedValues(:)), expected_accepted) ...
    && isequal(fieldnames(qc.Model), {'Status'}) && string(qc.Model.Status) == "not_provided", ...
    "run_matlab_gate:ComparisonProofQC", "Observation QC must remain complete without inventing model QC");
uncertainty = result.Uncertainty;
assert(string(result.UncertaintyType) == "standard-uncertainty" ...
    && string(result.UncertaintyUnit) == "degC" && isequaln(result.ConfidenceLevel, NaN) ...
    && string(uncertainty.Sides) == "observation" ...
    && string(uncertainty.Representation) == "magnitude" ...
    && string(uncertainty.Display) == "horizontal-line-segments" ...
    && isequal(sort(fieldnames(uncertainty.Observation)), sort({'Status'; 'Values'})) ...
    && string(uncertainty.Observation.Status) == "provided" ...
    && isequaln(uncertainty.Observation.Values(:), expected_uncertainty) ...
    && isequal(fieldnames(uncertainty.Model), {'Status'}) ...
    && string(uncertainty.Model.Status) == "not_provided" ...
    && isequal(uncertainty.GraphicsMask(:), graphics_mask), ...
    "run_matlab_gate:ComparisonProofUncertainty", ...
    "All observation magnitudes and graphics membership must be retained without model uncertainty");

drawnow;
axes_handle = result.Axes;
scatter_handle = result.Scatter;
assert(isscalar(axes_handle) && isgraphics(axes_handle, "axes") ...
    && isequal(ancestor(axes_handle, "figure"), figure_handle) ...
    && string(axes_handle.Visible) == "on" ...
    && string(axes_handle.XScale) == "linear" && string(axes_handle.YScale) == "linear" ...
    && string(axes_handle.XDir) == "normal" && string(axes_handle.YDir) == "normal" ...
    && isequal(axes_handle.XLim, axes_handle.YLim) ...
    && axes_handle.DataAspectRatio(1) == axes_handle.DataAspectRatio(2) ...
    && isscalar(scatter_handle) && isgraphics(scatter_handle, "scatter") ...
    && isequal(findall(axes_handle, "Type", "scatter"), scatter_handle) ...
    && isequal(scatter_handle.Parent, axes_handle) ...
    && string(scatter_handle.Visible) == "on" && string(scatter_handle.Marker) ~= "none" ...
    && all(scatter_handle.SizeData(:) > 0) ...
    && comparison_marker_painted(scatter_handle), ...
    "run_matlab_gate:ComparisonProofHandles", ...
    "Exactly one visible native scatter must belong to the same exported linear normal axes");
native_x = double(scatter_handle.XData(:));
native_y = double(scatter_handle.YData(:));
native_identity = scatter_handle.UserData;
assert(isequal(native_x, expected_observation(paired_mask)) ...
    && isequal(native_y, expected_model(paired_mask)) ...
    && isequal(native_identity.SourceRow(:), record_data.SourceRow(paired_mask)) ...
    && isequal(string(native_identity.RecordID(:)), string(record_data.RecordID(paired_mask))) ...
    && string(native_identity.SourceRowOrigin) == "call_entry_order", ...
    "run_matlab_gate:ComparisonProofScatter", ...
    "Native scatter coordinates and identity must match the same selected full records");
line_handles = result.UncertaintyGraphics;
selected_rows = find(graphics_mask);
owned_lines = findall(axes_handle, "Type", "line");
assert(numel(line_handles) == numel(selected_rows) ...
    && all(isgraphics(line_handles, "line")) ...
    && numel(owned_lines) == numel(line_handles) + 1 ...
    && isscalar(result.OneToOne) && isgraphics(result.OneToOne, "line") ...
    && isequal(result.OneToOne.Parent, axes_handle) ...
    && isequal(double(result.OneToOne.XData(:)), double(axes_handle.XLim(:))) ...
    && isequal(double(result.OneToOne.YData(:)), double(axes_handle.YLim(:))) ...
    && isempty(findall(axes_handle, "Type", "errorbar")), ...
    "run_matlab_gate:ComparisonProofLineCount", ...
    "Comparison uncertainty must contain only the actual horizontal native segments");
segments = cell(numel(line_handles), 1);
for segment_index = 1:numel(line_handles)
    source_row = selected_rows(segment_index);
    line_handle = line_handles(segment_index);
    line_identity = line_handle.UserData;
    line_x = double(line_handle.XData(:));
    line_y = double(line_handle.YData(:));
    expected_x = expected_observation(source_row) + [-1; 1]*expected_uncertainty(source_row);
    expected_y = repmat(expected_model(source_row), 2, 1);
    assert(isequal(line_handle.Parent, axes_handle) && string(line_handle.Visible) == "on" ...
        && string(line_handle.LineStyle) ~= "none" && line_handle.LineWidth > 0 ...
        && isequal(line_x, expected_x) && isequal(line_y, expected_y) ...
        && isequal(line_identity.SourceRow, record_data.SourceRow(source_row)) ...
        && string(line_identity.RecordID) == string(record_data.RecordID(source_row)) ...
        && string(line_identity.SourceRowOrigin) == "call_entry_order" ...
        && all(line_x >= axes_handle.XLim(1) & line_x <= axes_handle.XLim(2)) ...
        && all(line_y >= axes_handle.YLim(1) & line_y <= axes_handle.YLim(2)), ...
        "run_matlab_gate:ComparisonProofSegments", ...
        "Native horizontal endpoints, source identity and final limits must match observation uncertainty");
    segment = struct("source_row", line_identity.SourceRow, ...
        "record_id", string(line_identity.RecordID));
    segment.x_values = num2cell(line_x);
    segment.y_values = num2cell(line_y);
    segments{segment_index} = segment;
end
legend_title_string = result.Legend.Title.String;
if ischar(legend_title_string) && size(legend_title_string, 1) > 1
    legend_title_string = cellstr(legend_title_string);
end
legend_title_lines = string(legend_title_string);
assert(isscalar(result.Legend) && isgraphics(result.Legend) ...
    && isequal(ancestor(result.Legend, "figure"), figure_handle) ...
    && string(result.Legend.Visible) == "on" && string(result.Legend.Title.Visible) == "on" ...
    && isequal(legend_title_lines(:), ...
        ["Horizontal: observation standard uncertainty (degC)"; "Model uncertainty not provided"]) ...
    && string(axes_handle.XLabel.String) == expected_axis_labels(1) ...
    && string(axes_handle.YLabel.String) == expected_axis_labels(2), ...
    "run_matlab_gate:ComparisonProofNativeText", ...
    "Actual native text must identify units, horizontal observation uncertainty and absent model uncertainty");
metrics = result.Metrics;
expected_residual = expected_model(paired_mask) - expected_observation(paired_mask);
correlations = corrcoef(expected_observation(paired_mask), expected_model(paired_mask));
expected_metrics = [mean(expected_residual); mean(abs(expected_residual)); ...
    sqrt(mean(expected_residual.^2)); correlations(1, 2)];
actual_metrics = [metrics.Bias; metrics.MAE; metrics.RMSE; metrics.Correlation];
native_residual = native_y - native_x;
native_correlations = corrcoef(native_x, native_y);
native_metrics = [mean(native_residual); mean(abs(native_residual)); ...
    sqrt(mean(native_residual.^2)); native_correlations(1, 2)];
assert(metrics.PairedCount == sum(paired_mask) && string(metrics.QuantityUnit) == "degC" ...
    && all(isfinite(actual_metrics)) ...
    && isequal(native_metrics, expected_metrics) ...
    && all(abs(actual_metrics - expected_metrics) ...
        <= max(1e-12, 1e-12*max(abs(actual_metrics), abs(expected_metrics)))), ...
    "run_matlab_gate:ComparisonProofMetrics", ...
    "Returned metrics must match independently recomputed complete-pair statistics");

record_time = record_data.Time(:);
record_time.Format = "yyyy-MM-dd'T'HH:mm:ss'Z'";
record_evidence = struct("time_zone", string(record_time.TimeZone), ...
    "depth_unit", string(record_data.DepthUnit), "depth_direction", string(record_data.DepthDirection), ...
    "source_row_origin", string(record_data.SourceRowOrigin));
record_evidence.ids = cellstr(string(record_data.RecordID(:)));
record_evidence.time_utc = cellstr(string(record_time));
record_evidence.depth_m = num2cell(record_data.Depth(:));
record_evidence.source_rows = num2cell(record_data.SourceRow(:));
input_values = struct();
input_values.observation = num2cell(record_data.Observation(:));
input_values.model = num2cell(record_data.Model(:));
pairing = struct("rule", string(result.PairingRule), ...
    "unmatched_observation_count", result.UnmatchedObservationCount, ...
    "unmatched_model_count", result.UnmatchedModelCount, ...
    "duplicate_key_policy", string(result.DuplicateKeyPolicy));
pairing.observation_indices = num2cell(result.ObservationPairIndices(:));
pairing.model_indices = num2cell(result.ModelPairIndices(:));
pairing.finite_pair_mask = num2cell(result.FinitePairMask(:));
pairing.paired_mask = num2cell(result.PairedMask(:));
qc_observation = struct("status", string(qc.Observation.Status));
qc_observation.flags = cellstr(string(qc.Observation.Flags(:)));
qc_observation.accepted_values = cellstr(string(qc.AcceptedValues(:)));
qc_evidence = struct("policy", string(fixture.contract.qc_policy), ...
    "observation", qc_observation, "model", struct("status", string(qc.Model.Status)));
qc_evidence.accepted_mask = num2cell(result.QCAcceptedMask(:));
native_scatter = struct();
native_scatter.source_rows = num2cell(native_identity.SourceRow(:));
native_scatter.record_ids = cellstr(string(native_identity.RecordID(:)));
native_scatter.x_values = num2cell(native_x);
native_scatter.y_values = num2cell(native_y);
uncertainty_observation = struct("status", string(uncertainty.Observation.Status));
uncertainty_observation.values = num2cell(uncertainty.Observation.Values(:));
uncertainty_observation.missing_mask = num2cell(isnan(uncertainty.Observation.Values(:)));
uncertainty_evidence = struct("type", string(result.UncertaintyType), ...
    "unit", string(result.UncertaintyUnit), "representation", string(uncertainty.Representation), ...
    "confidence_level", result.ConfidenceLevel, "display", string(uncertainty.Display), ...
    "observation", uncertainty_observation, ...
    "model", struct("status", string(uncertainty.Model.Status)), ...
    "native_data_source", "UncertaintyGraphics.XData/YData");
uncertainty_evidence.graphics_mask = num2cell(uncertainty.GraphicsMask(:));
uncertainty_evidence.segments = segments;
paired_stats = struct("paired_count", metrics.PairedCount, ...
    "bias_model_minus_observation", metrics.Bias, "mean_absolute_error", metrics.MAE, ...
    "root_mean_square_error", metrics.RMSE, "pearson_correlation", metrics.Correlation);
evidence = struct("schema_version", 3, "figure_id", string(fixture.id), ...
    "fixture_id", string(input_snapshot.id), "fixture_sha256", input_snapshot.sha256, ...
    "matlab_release", "R" + string(version('-release')), "quantity_unit", string(metrics.QuantityUnit), ...
    "missing_policy", string(result.MissingPolicy), "records", record_evidence, ...
    "input_values", input_values, "pairing", pairing, "qc", qc_evidence, ...
    "native_data_source", "Scatter.XData/YData", "native_scatter", native_scatter, ...
    "uncertainty", uncertainty_evidence, "paired_stats", paired_stats);
evidence.dimension_order = {'observation'};
evidence.shape = {numel(record_data.Observation)};
end

function painted = comparison_marker_painted(scatter_handle)
painted = false;
alphas = {scatter_handle.MarkerFaceAlpha, scatter_handle.MarkerEdgeAlpha};
colors = {scatter_handle.MarkerFaceColor, scatter_handle.MarkerEdgeColor};
for paint_index = 1:2
    alpha = alphas{paint_index};
    if ~(isnumeric(alpha) && isreal(alpha) && isscalar(alpha) ...
            && isfinite(alpha) && alpha >= 0 && alpha <= 1)
        painted = false;
        return;
    end
    color = colors{paint_index};
    if (ischar(color) || isstring(color)) && isscalar(string(color)) && string(color) == "flat"
        rgb = scatter_handle.CData;
        color_painted = isnumeric(rgb) && isreal(rgb) && ismatrix(rgb) && size(rgb, 2) == 3 ...
            && any(size(rgb, 1) == [1 numel(scatter_handle.XData)]) ...
            && all(isfinite(rgb(:)) & rgb(:) >= 0 & rgb(:) <= 1);
    else
        color_painted = isnumeric(color) && isreal(color) && isvector(color) && numel(color) == 3 ...
            && all(isfinite(color(:)) & color(:) >= 0 & color(:) <= 1);
    end
    painted = painted || (alpha > 0 && color_painted);
end
end

function values = parse_utc_time(raw_values)
values = datetime(string(raw_values(:)), ...
    "InputFormat", "yyyy-MM-dd'T'HH:mm:ss'Z'", "TimeZone", "UTC");
assert(~any(isnat(values)) && all(diff(values) >= seconds(0)), ...
    "run_matlab_gate:Time", "Fixture times must parse as nondecreasing UTC");
assert(string(values.TimeZone) == "UTC", "run_matlab_gate:TimeZone", ...
    "Parsed fixture times must retain the UTC time zone");
end

function values = numeric_record_field(records, field_name)
values = NaN(numel(records), 1);
for index = 1:numel(records)
    value = records(index).(field_name);
    if ~isempty(value)
        assert(isnumeric(value) && isscalar(value) && isfinite(value), ...
            "run_matlab_gate:RecordField", ...
            "Record field %s must be scalar numeric or null", field_name);
        values(index) = double(value);
    end
end
end

function assert_numeric_coordinates(actual, expected)
actual = actual(:);
expected = expected(:);
assert(numel(actual) == numel(expected) && numel(actual) >= 2 ...
    && isreal(actual) && isreal(expected) && all(isfinite(actual)) && all(isfinite(expected)), ...
    "run_matlab_gate:NativeCoordinates", "Coordinate vectors must be finite and aligned");
endpoint_ulp = max(eps(abs([actual([1 end]); expected([1 end])])));
ulp = max(max(eps(abs(actual)), eps(abs(expected))), endpoint_ulp);
assert(all(abs(actual - expected) <= 4 * ulp), "run_matlab_gate:NativeCoordinates", ...
    "Native coordinates must match within 4 ULP in identical ruler units; no sample-interval tolerance");
end

function contract = science_contract(shape, dimension_order, value_unit, timezone, qc_status, uncertainty_status)
shape = double(shape(:)');
dimension_order = string(dimension_order(:)');
coordinates = struct();
for index = 1:numel(dimension_order)
    name = dimension_order(index);
    coordinate = struct("count", shape(index), "unit", "1", ...
        "direction", "increasing");
    if name == "depth"
        coordinate.unit = "m";
        coordinate.direction = "positive_down";
    elseif name == "time"
        coordinate.unit = "datetime";
        coordinate.timezone = timezone;
    end
    coordinates.(name) = coordinate;
end
contract = struct("schemaVersion", 1, "provided", true, "required", true, ...
    "dataType", "synthetic_fixture", "shape", shape, "rank", numel(shape), ...
    "dimensionOrder", dimension_order, "observationDimension", dimension_order(1), ...
    "coordinates", coordinates, "units", struct("value", value_unit), ...
    "missing", struct("status", "present", "policy", "preserve", ...
        "representation", "NaN", "masked_count", 0), ...
    "qc", struct("status", qc_status, "action", "preserve"), ...
    "uncertainty", struct("status", uncertainty_status), ...
    "unresolvedRequirements", strings(0, 1));
if any(dimension_order == "time")
    contract.timeZone = timezone;
end
end


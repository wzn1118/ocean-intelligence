function run_matlab_gate(fixture_directory, output_directory, nonce)
%RUN_MATLAB_GATE Execute trusted MATLAB runtime and artifact gates.
arguments
    fixture_directory (1,1) string
    output_directory (1,1) string
    nonce (1,1) string
end
assert(strlength(strtrim(nonce)) >= 32, "run_matlab_gate:Nonce", ...
    "Evaluator nonce must be nonblank and unpredictable");
assert(isfolder(fixture_directory), "run_matlab_gate:Fixtures", ...
    "Fixture directory does not exist");
assert(isfolder(output_directory), "run_matlab_gate:Output", ...
    "Evaluator must create the fresh output directory before MATLAB starts");

eval_directory = fileparts(mfilename("fullpath"));
asset_directory = fullfile(eval_directory, "..", "assets");
assert(isfolder(asset_directory), "run_matlab_gate:Assets", ...
    "MATLAB asset directory does not exist");
addpath(asset_directory);

old_visible = get(0, "DefaultFigureVisible");
visibility_cleanup = onCleanup(@() set(0, "DefaultFigureVisible", old_visible));
set(0, "DefaultFigureVisible", "off");
theme = oi_ocean_theme();
entries = struct([]);

[temperature_fixture, temperature_input] = read_fixture(fixture_directory, ...
    "crossed_time_depth_temperature.json", output_directory);
temperature_time = parse_utc_time(temperature_fixture.coordinates.time.values);
temperature_depth = double(temperature_fixture.coordinates.depth.values(:));
temperature_values = double(temperature_fixture.variables.temperature.values);
temperature_qc = string_grid(temperature_fixture.variables.qc.values, size(temperature_values));
temperature_uncertainty = double(temperature_fixture.variables.temperature_standard_uncertainty.values);
temperature_entry = export_plot(output_directory, ...
    "crossed-time-depth-temperature", temperature_fixture.title, theme, ...
    @(axes_handle) oi_plot_hovmoller(axes_handle, temperature_time, ...
        temperature_depth, temperature_values, struct( ...
        "TimeZone", "UTC", "DepthUnit", "m", ...
        "QuantityLabel", "Temperature", "QuantityUnit", "degC", ...
        "ColorLimits", [12 19], "MissingPolicy", "preserve", ...
        "QCFlags", temperature_qc, "QCPolicy", "preserve", ...
        "UncertaintyValues", temperature_uncertainty, ...
        "UncertaintyType", temperature_fixture.variables.temperature_standard_uncertainty.type, ...
        "UncertaintyUnit", temperature_fixture.variables.temperature_standard_uncertainty.unit, ...
        "Theme", theme, "Title", temperature_fixture.title)), ...
    science_contract([numel(temperature_depth) numel(temperature_time)], ...
        ["depth" "time"], "degC", "UTC", "present", "present"), ...
    temperature_fixture, temperature_input);
entries = append_entry(entries, temperature_entry);

[profile_fixture, profile_input] = read_fixture(fixture_directory, ...
    "repeat_cast_salinity_profiles.json", output_directory);
profile_depth = double(profile_fixture.coordinates.depth.values(:));
profile_values = double(profile_fixture.variables.salinity.values);
profile_labels = string(profile_fixture.coordinates.time.values(:));
profile_qc = string_grid(profile_fixture.variables.qc.values, size(profile_values));
profile_uncertainty = double(profile_fixture.variables.salinity_standard_uncertainty.values);
profile_entry = export_plot(output_directory, ...
    "repeat-cast-salinity-profiles", profile_fixture.title, theme, ...
    @(axes_handle) oi_plot_profile(axes_handle, profile_depth, ...
        profile_values, struct("QuantityLabel", "Salinity", ...
        "QuantityUnit", "g kg-1", "DepthUnit", "m", ...
        "VerticalReference", "synthetic sea surface", ...
        "SeriesLabels", profile_labels, "MissingPolicy", "preserve", ...
        "QCFlags", profile_qc, "QCPolicy", "preserve", ...
        "UncertaintyValues", profile_uncertainty, ...
        "UncertaintyType", profile_fixture.variables.salinity_standard_uncertainty.type, ...
        "UncertaintyUnit", profile_fixture.variables.salinity_standard_uncertainty.unit, ...
        "UncertaintyDisplay", "metadata", ...
        "Theme", theme, "Title", profile_fixture.title)), ...
    science_contract([numel(profile_depth) numel(profile_labels)], ...
        ["depth" "time"], "g kg-1", "UTC", "present", "present"), ...
    profile_fixture, profile_input);
entries = append_entry(entries, profile_entry);

[paired_fixture, paired_input] = read_fixture(fixture_directory, ...
    "paired_observation_model.json", output_directory);
records = paired_fixture.records;
observations = numeric_record_field(records, "observation_degC");
model_values = numeric_record_field(records, "model_degC");
sample_labels = reshape(string({records.id}), [], 1);
entries = append_entry(entries, export_plot(output_directory, ...
    "paired-observation-model", paired_fixture.title, theme, ...
    @(axes_handle) oi_plot_comparison(axes_handle, observations, ...
        model_values, struct("QuantityUnit", "degC", ...
        "ObservationLabel", "Observation", "ModelLabel", "Model", ...
        "SampleLabels", sample_labels, "MissingPolicy", "preserve", ...
        "Theme", theme, "Title", paired_fixture.title)), ...
    science_contract(numel(records), "observation", "degC", "UTC", ...
        "present", "present")));

observation_time = temperature_time;
observation_values = temperature_values(3, :)';
uncertainty = temperature_uncertainty(3, :)';
interactive_ids = "temp-050m-" + compose("%03d", (1:numel(observation_time))');
station = "Synthetic mooring" + strings(numel(observation_time), 1);
qc = temperature_qc(3, :)';
observation_table = table(observation_time, observation_values, uncertainty, ...
    interactive_ids, station, qc, 'VariableNames', ...
    ["Time" "Value" "Uncertainty" "ObservationID" "Station" "QCFlag"]);
interactive_output = interactive_timeseries_native_template(observation_table, ...
    fullfile(output_directory, "paired-interactive"), "Interactive", true, ...
    "ExportMode", "graphics", "ExportSVG", true, ...
    "Title", "温度时间序列 / Temperature time series", ...
    "ValueLabel", "Temperature", "ValueUnit", "degC", ...
    "UncertaintyType", "standard-deviation", "UncertaintyUnit", "degC");
assert(interactive_output.HeadlessFallbackUsed, ...
    "run_matlab_gate:HeadlessFallback", ...
    "Batch path must use the deterministic headless fallback");
tip_text = interactive_output.DataCursorUpdateFcn([], ...
    struct("Target", interactive_output.Lines(1), "DataIndex", 1));
assert(~isequal(tip_text, {'Data tip unavailable'}), ...
    "run_matlab_gate:DataTip", "Stable-ID data tip lookup failed");
interactive_output.Lines(1).BrushData = [1; zeros(numel(observation_time) - 2, 1); 1];
selected_ids = string(interactive_output.GetSelectedObservationIDs());
assert(isequal(selected_ids, interactive_ids([1 end])), ...
    "run_matlab_gate:Brush", "Brush selection did not preserve stable IDs");
interactive_output.ClearBrushSelection();
assert(isempty(interactive_output.GetSelectedObservationIDs()), ...
    "run_matlab_gate:BrushClear", "Brush selection did not clear");
interactive_entry = interactive_output.ManifestEntry;
interactive_entry.scientific_data_contract = science_contract( ...
    numel(observation_time), "time", "degC", "UTC", "present", "present");
interactive_entry.scientific_data_contract.missing.total_count = numel(observation_time);
interactive_entry.scientific_data_contract.missing.valid_count = interactive_output.ValidCount;
interactive_entry.scientific_data_contract.missing.missing_count = interactive_output.MissingCount;
entries = append_entry(entries, interactive_entry);
close(interactive_output.Figure);

figure_ids = string({entries.id});
[~, order] = sort(figure_ids);
entries = entries(order);
input_fixtures = [temperature_input; profile_input; paired_input];
for input_index = 1:numel(input_fixtures)
    verify_input_snapshot(output_directory, input_fixtures(input_index));
end
manifest = oi_write_manifest(fullfile(output_directory, "figures.json"), entries);
assert(manifest.execution_verified && manifest.runtime_status == "ready" ...
    && manifest.artifact_validation.status == "passed", ...
    "run_matlab_gate:Manifest", "Runtime manifest did not pass validation");

runtime_record = struct( ...
    "schema_version", 1, ...
    "nonce", nonce, ...
    "runtime", "MathWorks MATLAB", ...
    "success", true, ...
    "matlab_version", string(version), ...
    "matlab_release", "R" + string(version('-release')), ...
    "jvm_available", logical(usejava("jvm")), ...
    "desktop_available", logical(usejava("desktop")), ...
    "batch_startup_option_used", batch_mode(), ...
    "fixture_ids", ["crossed-time-depth-temperature"; ...
        "repeat-cast-salinity-profiles"; "paired-observation-model"], ...
    "input_fixtures", input_fixtures, ...
    "interaction", struct("datatip_verified", true, ...
        "brush_stable_ids_verified", true, "headless_fallback_verified", true), ...
    "manifest", "figures.json");
write_json(fullfile(output_directory, "matlab-runtime.json"), runtime_record);
clear visibility_cleanup;
fprintf("MATLAB_EVAL_GATE=passed\n");
fprintf("MATLAB_EVAL_FIGURES=%d\n", numel(entries));
end

function [payload, snapshot] = read_fixture(directory, name, output_directory)
path = fullfile(directory, name);
assert(isfile(path), "run_matlab_gate:FixtureMissing", ...
    "Fixture is missing: %s", path);
file_handle = fopen(path, "rb");
assert(file_handle >= 0, "run_matlab_gate:FixtureRead", "Cannot read fixture: %s", path);
read_cleanup = onCleanup(@() fclose(file_handle));
content = fread(file_handle, Inf, "*uint8");
clear read_cleanup;
assert(~isempty(content), "run_matlab_gate:FixtureRead", "Fixture is empty: %s", path);
input_directory = fullfile(output_directory, "fixture-inputs");
if ~isfolder(input_directory)
    [created, message] = mkdir(input_directory);
    assert(created, "run_matlab_gate:FixtureDirectory", "%s", message);
end
snapshot_path = fullfile(input_directory, name);
assert(~isfile(snapshot_path), "run_matlab_gate:StaleFixtureSnapshot", ...
    "Refusing to overwrite an input snapshot: %s", snapshot_path);
file_handle = fopen(snapshot_path, "wb");
assert(file_handle >= 0, "run_matlab_gate:FixtureWrite", ...
    "Cannot write input snapshot: %s", snapshot_path);
write_cleanup = onCleanup(@() fclose(file_handle));
written = fwrite(file_handle, content, "uint8");
assert(written == numel(content), "run_matlab_gate:FixtureWrite", ...
    "Input snapshot was not fully written: %s", snapshot_path);
clear write_cleanup;
payload = jsondecode(native2unicode(content', 'UTF-8'));
snapshot = struct("id", string(payload.id), "file", "fixture-inputs/" + name, ...
    "source_file", name, "bytes", numel(content), ...
    "sha256", string(oi_sha256_file(snapshot_path)));
verify_input_snapshot(output_directory, snapshot);
end

function verify_input_snapshot(output_directory, snapshot)
snapshot_path = fullfile(output_directory, snapshot.file);
file_info = dir(snapshot_path);
assert(isscalar(file_info) && ~file_info.isdir && file_info.bytes == snapshot.bytes ...
    && strcmpi(oi_sha256_file(snapshot_path), snapshot.sha256), ...
    "run_matlab_gate:FixtureChanged", ...
    "Consumed fixture snapshot changed during execution: %s", snapshot_path);
end

function values = parse_utc_time(raw_values)
values = datetime(string(raw_values(:)), ...
    "InputFormat", "yyyy-MM-dd'T'HH:mm:ss'Z'", "TimeZone", "UTC");
assert(~any(isnat(values)) && all(diff(values) >= seconds(0)), ...
    "run_matlab_gate:Time", "Fixture times must parse as nondecreasing UTC");
assert(string(values.TimeZone) == "UTC", "run_matlab_gate:TimeZone", ...
    "Parsed fixture times must retain the UTC time zone");
end

function values = numeric_record_field(records, field_name)
values = NaN(numel(records), 1);
for index = 1:numel(records)
    value = records(index).(field_name);
    if ~isempty(value)
        assert(isnumeric(value) && isscalar(value) && isfinite(value), ...
            "run_matlab_gate:RecordField", ...
            "Record field %s must be scalar numeric or null", field_name);
        values(index) = double(value);
    end
end
end

function values = string_grid(raw, expected_shape)
if iscell(raw) && numel(raw) == expected_shape(1) ...
        && all(cellfun(@iscell, raw(:)))
    values = strings(expected_shape);
    for row_index = 1:expected_shape(1)
        row_values = string(raw{row_index});
        assert(numel(row_values) == expected_shape(2), ...
            "run_matlab_gate:StringGridShape", "String grid row width does not match the data");
        values(row_index, :) = reshape(row_values, 1, []);
    end
else
    values = string(raw);
end
assert(isequal(size(values), expected_shape) && all(~ismissing(values), "all"), ...
    "run_matlab_gate:StringGridShape", "String grid must match the data shape without missing labels");
end

function entry = export_plot(output_directory, identifier, title_text, theme, plotter, contract, fixture, input_snapshot)
figure_handle = oi_figure(2400, 1500, "off");
cleanup = onCleanup(@() close_if_valid(figure_handle));
page_size_inches = [8 5];
figure_handle.Units = "inches";
figure_handle.Position(3:4) = page_size_inches;
figure_handle.PaperUnits = "inches";
figure_handle.PaperPosition = [0 0 page_size_inches];
figure_handle.PaperSize = page_size_inches;
figure_handle.PaperPositionMode = "manual";
page_margin = 0.4 ./ page_size_inches;
layout_handle = tiledlayout(figure_handle, 1, 1, ...
    "Padding", "loose", "TileSpacing", "compact");
layout_handle.Units = "normalized";
layout_handle.OuterPosition = [page_margin 1 - 2 * page_margin];
axes_handle = nexttile(layout_handle);
result = plotter(axes_handle);
assert(result.ValidCount + result.MissingCount == prod(contract.shape), ...
    "run_matlab_gate:Counts", "Plot counts must match fixture shape");
oi_apply_axes(axes_handle, theme);
if isfield(result, "Legend") && isscalar(result.Legend) && isgraphics(result.Legend)
    legend_location = string(result.Legend.Location);
    if any(legend_location == ["northoutside" "southoutside" "eastoutside" "westoutside"])
        result.Legend.Layout.Tile = erase(legend_location, "outside");
    end
end
if isfield(result, "Colorbar") && isscalar(result.Colorbar) && isgraphics(result.Colorbar)
    result.Colorbar.Layout.Tile = "east";
end
drawnow;
entry = oi_export_figure(figure_handle, output_directory, identifier, ...
    2400, 1500, 300, "Title", title_text, ...
    "Source", "Ocean Intelligence MATLAB full-score fixture", ...
    "Theme", theme.Name, "ExportSVG", true);
measured_margins_inches = entry.rendering_evidence.normalized_margins ...
    .* [page_size_inches page_size_inches];
assert(all(measured_margins_inches >= 0.1), ...
    "run_matlab_gate:PageMargins", ...
    "Final layout must retain at least 0.1 inch on every page edge: %s", ...
    mat2str(measured_margins_inches, 5));
contract.missing.total_count = prod(contract.shape);
contract.missing.valid_count = result.ValidCount;
contract.missing.missing_count = result.MissingCount;
if nargin == 8
    contract.plot_data_evidence = measure_grid_plot_data(result, fixture, input_snapshot);
end
entry.scientific_data_contract = contract;
close(figure_handle);
clear cleanup;
end

function evidence = measure_grid_plot_data(result, fixture, input_snapshot)
time_utc = string(fixture.coordinates.time.values(:));
depth_m = double(fixture.coordinates.depth.values(:));
if string(fixture.id) == "crossed-time-depth-temperature"
    variable_name = "temperature";
    native_source = "Image.CData";
    assert(isgraphics(result.Image, "image"), "run_matlab_gate:NativeImage", ...
        "Hovmoller evidence requires the native image");
    native_values = double(result.Image.CData);
    expected_time = double(ruler2num(parse_utc_time(fixture.coordinates.time.values), result.Axes.XAxis));
    native_time = double(ruler2num(result.Image.XData, result.Axes.XAxis));
    assert(isvector(native_time) && numel(native_time) >= 2 ...
        && size(native_values, 2) == numel(expected_time) ...
        && string(result.Axes.XLim.TimeZone) == "UTC" ...
        && (~isdatetime(result.Image.XData) || string(result.Image.XData.TimeZone) == "UTC"), ...
        "run_matlab_gate:NativeCoordinates", "Image columns and ruler timezone must preserve fixture coordinates");
    assert_numeric_coordinates(native_time([1 end]), expected_time([1 end]));
    native_centers = linspace(native_time(1), native_time(end), size(native_values, 2))';
    assert_numeric_coordinates(native_centers, expected_time);
    native_depth = double(result.Image.YData(:));
    expected_depth = depth_m;
    if numel(native_depth) == 2
        expected_depth = expected_depth([1 end]);
    end
    assert(isequaln(native_depth, expected_depth), "run_matlab_gate:NativeCoordinates", ...
        "Image coordinates must preserve fixture order and extent");
    assert(isequaln(logical(result.Image.AlphaData), isfinite(native_values)), ...
        "run_matlab_gate:NativeMissingMask", "Image AlphaData must preserve missing cells");
elseif string(fixture.id) == "repeat-cast-salinity-profiles"
    variable_name = "salinity";
    native_source = "Lines.XData";
    assert(numel(result.Lines) == numel(time_utc) && all(isgraphics(result.Lines, "line")) ...
        && isempty(result.UncertaintyHandles), "run_matlab_gate:NativeLines", ...
        "Profile evidence requires every native series and metadata-only uncertainty");
    native_values = NaN(numel(depth_m), numel(time_utc));
    for series_index = 1:numel(result.Lines)
        native_values(:, series_index) = double(result.Lines(series_index).XData(:));
        assert(isequaln(double(result.Lines(series_index).YData(:)), depth_m) ...
            && isequaln(string(result.Lines(series_index).DisplayName), time_utc(series_index)), ...
            "run_matlab_gate:NativeCoordinates", "Profile depth and series order must match the fixture");
    end
else
    error("run_matlab_gate:PlotDataScope", "Unsupported native plot evidence fixture");
end
variable = fixture.variables.(char(variable_name));
uncertainty = fixture.variables.(char(variable_name + "_standard_uncertainty"));
expected_values = double(variable.values);
expected_qc = string_grid(fixture.variables.qc.values, size(expected_values));
expected_uncertainty = double(uncertainty.values);
assert(isequaln(native_values, expected_values) ...
    && isequaln(result.MissingMask, isnan(expected_values)) ...
    && isequaln(result.ValidCount, sum(isfinite(expected_values), "all")) ...
    && isequaln(result.MissingCount, sum(isnan(expected_values), "all")) ...
    && isequaln(result.Interpolated, false), ...
    "run_matlab_gate:NativeValues", "Native values and missing masks must exactly preserve the input");
assert(isequaln(result.QCProvided, true) && isequaln(result.QCFlags, expected_qc) ...
    && isequaln(string(result.QCPolicy), string(fixture.variables.qc.policy)) ...
    && isequaln(string(result.QCPolicy), "preserve"), ...
    "run_matlab_gate:NativeQC", "Result QC must preserve every input flag including suspect");
assert(isequaln(result.UncertaintyPresent, true) ...
    && isequaln(result.UncertaintyValues, expected_uncertainty) ...
    && isequaln(string(result.UncertaintyType), string(uncertainty.type)) ...
    && isequaln(string(result.UncertaintyUnit), string(uncertainty.unit)) ...
    && isequaln(string(result.UncertaintyDisplay), "metadata"), ...
    "run_matlab_gate:NativeUncertainty", "Result uncertainty must preserve input values, type and unit without bands");
assert(isequaln(string(result.QuantityUnit), string(variable.unit)) ...
    && isequaln(string(result.DepthUnit), string(fixture.coordinates.depth.unit)) ...
    && isequaln(string(result.MissingPolicy), string(variable.missing_policy)) ...
    && isequaln(string(result.Axes.YDir), "reverse"), ...
    "run_matlab_gate:NativeUnits", "Native result units, missing policy and depth direction must match inputs");
evidence = struct("schema_version", 1, "figure_id", string(fixture.id), "fixture_id", string(input_snapshot.id), ...
    "fixture_sha256", input_snapshot.sha256, "matlab_release", "R" + string(version('-release')), ...
    "dimension_order", ["depth" "time"], "shape", size(native_values), ...
    "time_utc", time_utc, "depth_m", depth_m, "depth_unit", string(result.DepthUnit), ...
    "quantity_unit", string(result.QuantityUnit), "missing_policy", string(result.MissingPolicy), ...
    "native_data_source", native_source, "native_values", native_values, ...
    "missing_mask", result.MissingMask, "input_match_asserted", true, ...
    "qc", struct("provided", result.QCProvided, "policy", string(result.QCPolicy), ...
        "flags", result.QCFlags), ...
    "uncertainty", struct("present", result.UncertaintyPresent, ...
        "type", string(result.UncertaintyType), "unit", string(result.UncertaintyUnit), ...
        "display", string(result.UncertaintyDisplay), "values", result.UncertaintyValues));
end

function assert_numeric_coordinates(actual, expected)
actual = actual(:);
expected = expected(:);
assert(numel(actual) == numel(expected) && numel(actual) >= 2 ...
    && isreal(actual) && isreal(expected) && all(isfinite(actual)) && all(isfinite(expected)), ...
    "run_matlab_gate:NativeCoordinates", "Coordinate vectors must be finite and aligned");
endpoint_ulp = max(eps(abs([actual([1 end]); expected([1 end])])));
ulp = max(max(eps(abs(actual)), eps(abs(expected))), endpoint_ulp);
assert(all(abs(actual - expected) <= 4 * ulp), "run_matlab_gate:NativeCoordinates", ...
    "Native coordinates must match within 4 ULP in identical ruler units; no sample-interval tolerance");
end

function contract = science_contract(shape, dimension_order, value_unit, timezone, qc_status, uncertainty_status)
shape = double(shape(:)');
dimension_order = string(dimension_order(:)');
coordinates = struct();
for index = 1:numel(dimension_order)
    name = dimension_order(index);
    coordinate = struct("count", shape(index), "unit", "1", ...
        "direction", "increasing");
    if name == "depth"
        coordinate.unit = "m";
        coordinate.direction = "positive_down";
    elseif name == "time"
        coordinate.unit = "datetime";
        coordinate.timezone = timezone;
    end
    coordinates.(name) = coordinate;
end
contract = struct("schemaVersion", 1, "provided", true, "required", true, ...
    "dataType", "synthetic_fixture", "shape", shape, "rank", numel(shape), ...
    "dimensionOrder", dimension_order, "observationDimension", dimension_order(1), ...
    "coordinates", coordinates, "units", struct("value", value_unit), ...
    "missing", struct("status", "present", "policy", "preserve", ...
        "representation", "NaN", "masked_count", 0), ...
    "qc", struct("status", qc_status, "action", "preserve"), ...
    "uncertainty", struct("status", uncertainty_status), ...
    "unresolvedRequirements", strings(0, 1));
if any(dimension_order == "time")
    contract.timeZone = timezone;
end
end

function entries = append_entry(entries, entry)
if isempty(entries)
    entries = entry;
else
    entries(end + 1, 1) = entry;
end
end

function close_if_valid(figure_handle)
if isgraphics(figure_handle)
    close(figure_handle);
end
end

function value = batch_mode()
value = false;
if exist("batchStartupOptionUsed", "file") == 2 ...
        || exist("batchStartupOptionUsed", "builtin") == 5
    value = logical(batchStartupOptionUsed());
end
end

function write_json(path, payload)
encoded = jsonencode(payload);
file_id = fopen(path, "w", "n", "UTF-8");
assert(file_id >= 0, "run_matlab_gate:Write", ...
    "Unable to open JSON output: %s", path);
cleanup = onCleanup(@() fclose(file_id));
written = fwrite(file_id, encoded, "char");
assert(written == strlength(string(encoded)), ...
    "run_matlab_gate:Write", "Incomplete JSON write: %s", path);
clear cleanup;
end

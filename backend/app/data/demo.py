def _catalog_event(
    *,
    event_id: str,
    event_type: str,
    title: str,
    summary: str,
    region: str,
    centroid: tuple[float, float],
    radius_km: float,
    start_days: int,
    status: str,
    severity: float,
    severity_label: str,
    confidence: float,
    affected_area_km2: float,
    variables: list[str],
    sources: list[str],
    observations: list[tuple[str, str, float, float, str, str, float]],
    reasoning: list[tuple[str, str, list[int], list[str], float]],
    potential_impacts: list[str],
    uncertainty: str,
) -> OceanEvent:
    evidence = [
        _evidence(event_id, str(index), *observation)
        for index, observation in enumerate(observations, start=1)
    ]
    reasoning_chain = [
        ReasoningStep(
            order=index,
            claim=claim,
            mechanism=mechanism,
            evidence_ids=[f"{event_id}-E{evidence_index}" for evidence_index in evidence_indexes],
            reference_ids=reference_ids,
            confidence=step_confidence,
        )
        for index, (claim, mechanism, evidence_indexes, reference_ids, step_confidence) in enumerate(
            reasoning,
            start=1,
        )
    ]

    return OceanEvent(
        id=event_id,
        type=event_type,
        title=title,
        summary=summary,
        region=region,
        centroid=centroid,
        radius_km=radius_km,
        started_at=NOW - timedelta(days=start_days),
        status=status,
        severity=severity,
        severity_label=severity_label,
        confidence=confidence,
        affected_area_km2=affected_area_km2,
        variables=variables,
        sources=sources,
        references=REFERENCES[event_type],
        evidence=evidence,
        reasoning_chain=reasoning_chain,
        timeline=_timeline(start_days),
        potential_impacts=potential_impacts,
        uncertainty=uncertainty,
        validation_state="scenario",
    )



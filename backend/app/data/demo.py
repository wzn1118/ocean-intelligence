def _series(
    observed: float,
    baseline: float,
    days: int = 14,
    growth: float = 1.0,
) -> list[DataPoint]:
    points: list[DataPoint] = []
    for index in range(days):
        progress = index / (days - 1)
        seasonal = sin(index * 0.65) * abs(observed - baseline) * 0.08
        value = baseline + (observed - baseline) * (progress**growth) + seasonal
        points.append(
            DataPoint(
                timestamp=NOW - timedelta(days=days - 1 - index),
                value=round(value, 3),
                baseline=baseline,
            )
        )
    return points


def _evidence(
    event_id: str,
    suffix: str,
    source: str,
    variable: str,
    observed: float,
    baseline: float,
    unit: str,
    method: str,
    confidence: float,
) -> Evidence:
    return Evidence(
        id=f"{event_id}-E{suffix}",
        source=source,
        variable=variable,
        observed=observed,
        baseline=baseline,
        anomaly=round(observed - baseline, 3),
        unit=unit,
        timestamp=NOW - timedelta(hours=int(suffix) * 2),
        method=method,
        confidence=confidence,
        series=_series(observed, baseline),
        sample_count=14,
        temporal_span_hours=13 * 24,
        validation_state="scenario",
    )


